public enum HarmfulTileType
{
    None,
    Ice,       // блокирует свайп, пока не разморозится сама или матчем по соседству (переиспользует Item.Freeze/isFrozen)
    Spike,     // фиксированный урон герою каждый ход, пока фишка на поле
    Trap,      // выглядит как обычный гем, но матч по ней наносит урон герою вместо пользы
    Anchor,    // не уничтожается обычным матчем — снимается только спец-скиллом (Elves T2) или N матчей подряд по соседству
    Cursed,    // если не убрать матчем за value ходов — заражает случайного соседа и сама начинает отсчёт заново
    BloodMark, // пока хоть одна такая фишка на поле — весь урон, получаемый игроком, увеличен на value%
    Rotten,    // каждый ход заражает одного случайного соседа (превращает в такой же Rotten), пока её не уберут матчем
    Chaos      // при попадании в матч меняет цвет всех живых соседей на случайный (не входящих в этот же матч)
}

[System.Serializable]
public class HarmfulTileSpawnRule
{
    public HarmfulTileType type;
    public int count = 1;          // сколько таких фишек заспавнить в начале боя
    public int value = 1;          // Ice/Anchor/Cursed: длительность/порог в ходах; Spike/Trap: урон герою; BloodMark: % урона игроку
}
