// Тип узла нового roguelike-режима (см. project-future-backlog #7, вариант C+A: мутация поля +
// ветвящийся путь) — отдельный от Death Dungeon режим: тот же принцип "тип узла = бонус/усложнение
// ВОКРУГ боя", но softer stakes (поражение = просто выход из рана, героям ничего не грозит, см.
// MutationDungeonManager) и с выбором из 2-3 следующих узлов на каждом шаге вместо фиксированной
// последовательности.
public enum MutationDungeonNodeType
{
    Battle,   // обычный бой с активной мутацией поля этого узла
    Elite,    // усложнённый бой (враг заметно сильнее) + мутация, лучше награда
    Rest,     // без боя — лечим отряд на % макс. HP, продолжаем путь
    Treasure, // без боя — гарантированный доп-предмет
    Boss,     // финальный узел рана — без мутации, победа завершает ран
}
